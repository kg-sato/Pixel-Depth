"""Write src/PetVoxelsData.luau from design3d/pets/pets.json and design3d/pets/out/ids.txt (run after build_pets.py and the upload)."""
import json, os
here = os.path.dirname(os.path.abspath(__file__)); game = os.path.dirname(os.path.dirname(here))
pets = json.load(open(os.path.join(here, "pets.json")))
ids = dict(l.split() for l in open(os.path.join(here, os.environ.get("PET_OUT", "out_b"), "ids.txt")) if l.strip())
L = ["-- Generated by design3d/pets/make_lua.py from design3d/pets/pets.json and out/ids.txt. Do not edit by hand.",
     "-- name = { id (Model asset: MeshParts named Part__Role), vox (studs per voxel), height (voxels), palette (Role -> Color3), pivots (Part -> joint, studs, +Z front, feet at y 0) }",
     "return {"]
for p in pets:
    s = p["vox"]; cells = [c for vs in p["parts"].values() for c in vs]
    xs = [c[0] for c in cells]; zs = [c[2] for c in cells]
    cx, cz = (min(xs) + max(xs) + 1) / 2, (min(zs) + max(zs) + 1) / 2
    pal = ", ".join(f'{k} = Color3.fromHex("{v}")' for k, v in p["palette"].items())
    piv = ", ".join(f'["{k}"] = Vector3.new({(v[0] + 0.5 - cx) * s:.3f}, {v[1] * s:.3f}, {(v[2] + 0.5 - cz) * s:.3f})' for k, v in p["pivots"].items())
    L.append(f'\t["{p["name"]}"] = {{ id = {ids[p["name"].replace(" ", "")]}, vox = {s}, height = {p["height"]}, palette = {{ {pal} }}, pivots = {{ {piv} }} }},')
L.append("}")
open(os.path.join(game, "src", "PetVoxelsData.luau"), "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
print("wrote", len(pets))
