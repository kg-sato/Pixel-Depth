"""Write src/PetRigData.luau from design3d/pets/rigs.json (pet_plate.py) and design3d/pets/out_plate/ids.txt (the uploads).
    python design3d/pets/make_rig_lua.py"""
import json, os
here = os.path.dirname(os.path.abspath(__file__)); game = os.path.dirname(os.path.dirname(here))
rigs = json.load(open(os.path.join(here, "rigs.json")))
ids = dict(l.split() for l in open(os.path.join(here, "out_plate", "ids.txt")) if len(l.split()) == 2)
vp = os.path.join(here, "out_vox", "ids.txt")  # the hi-detail voxel pets (pet_vox.py) replace the plate uploads as they land
if os.path.exists(vp): ids.update(dict(l.split() for l in open(vp) if len(l.split()) == 2))
v3 = lambda v: "Vector3.new(%.3f, %.3f, %.3f)" % tuple(v)
L = ["-- Generated by design3d/pets/make_rig_lua.py from design3d/pets/rigs.json and out_plate/ids.txt. Do not edit by hand.",
     "-- The v16 plate pets (Master Directive v16, the owner's Lure a Pet reference; design3d/pets/pet_plate.py): one MeshPart per bone",
     "-- named Part__Tex / Part__Tex2 (vertex-coloured; Color stays white) or Part__Glow (Neon). name = { id (Model asset), height,",
     "-- size (studs, x / y up / z forward), glow (Color3), parts = { Part = { parent, pivot (+Z front, feet at 0), group } },",
     "-- axes = { RingN = spin axis }, anchors = { name = { Part, position } } }",
     "return {"]
for name, d in rigs.items():
    key = name.replace(" ", "")
    if key not in ids or name == "PlateTest": continue
    parts = ", ".join('["%s"] = { %s, %s, "%s" }' % (p, ('"%s"' % d["parent"][p]) if d["parent"].get(p) else "nil", v3(d["pivots"][p]), d["groups"].get(p, "body")) for p in d["pivots"])
    axes = ", ".join('["%s"] = %s' % (k, v3(v)) for k, v in d.get("axes", {}).items())
    anchors = ", ".join('["%s"] = { "%s", %s }' % (k, v[0], v3(v[1])) for k, v in d.get("anchors", {}).items())
    glow = d["palette"].get("Glow", "#ffffff")
    crystal = d["palette"].get("Crystal", glow)
    L.append('\t["%s"] = { id = %s, height = %.2f, size = %s, glow = Color3.fromHex("%s"), crystal = Color3.fromHex("%s"),%s parts = { %s }, axes = { %s }, anchors = { %s } },'
             % (name, ids[key], d["height"], v3(d["size"]), glow, crystal, " vox = true," if "cells" in d else "", parts, axes, anchors))
L.append("}")
open(os.path.join(game, "src", "PetRigData.luau"), "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
print("wrote", len(L) - 7)
