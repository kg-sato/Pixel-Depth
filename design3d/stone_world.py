# the sculpted ledges: stacks of rounded slabs set into both walls, each layer a little in or out of the one below
def wall_x(side, z, h):
    """the x where the wall on that side (-1 left, +1 right) reaches height h"""
    for x in np.arange(20.0, 120.0, 0.5):
        if wall(side * x, z) >= h: return side * x
    return side * 120.0


