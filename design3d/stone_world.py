"""The Stone Pickaxe setting: a shallow river in a canyon of pale layered limestone (reference: refs/forge/sheets/
stone_setting_s11.png; scene bible "Stone").
    python design3d/stone_world.py
Writes, from ONE height function: design3d/tex/stone_terrain.mjs (near river floor and far canyon), stone_floor.png (gravel
bars, river bed, wall strata painted from above by height), stone_far.png, two skies (summer, winter) and
src/ForgeStoneMap.luau (pebbles, boulders, alders, bushes, reeds, flowers). Authoring space: x to screen right, y up,
z toward the camera; the action is on a gravel bar at the origin; the river runs away from the camera on the left."""
import json, pathlib
import numpy as np
from PIL import Image, ImageFilter

here = pathlib.Path(__file__).resolve().parent
tex = here / "tex"; tex.mkdir(exist_ok=True)
WATER_Y = -0.5
NEAR = (-110.0, -170.0, 110.0, 50.0)
FAR = (-1000.0, -1650.0, 1000.0, 150.0)
N = 96


def vnoise(x, y, seed=0, px=None):
    xi = np.floor(x).astype(np.int64); yi = np.floor(y).astype(np.int64)
    xf = x - xi; yf = y - yi

    def h(a, b):
        if px: a = a % px
        n = (a * 374761393 + b * 668265263 + seed * 1442695041) & 0xFFFFFFFF
        n = ((n ^ (n >> 13)) * 1274126177) & 0xFFFFFFFF
        return ((n ^ (n >> 16)) & 0xFFFF) / 65535.0
    u = xf * xf * (3 - 2 * xf); v = yf * yf * (3 - 2 * yf)
    return (h(xi, yi) * (1 - u) + h(xi + 1, yi) * u) * (1 - v) + (h(xi, yi + 1) * (1 - u) + h(xi + 1, yi + 1) * u) * v


def fbm(x, y, seed=0, octaves=4, px=None):
    s, a, f, tot = 0.0, 0.5, 1.0, 0.0
    for o in range(octaves):
        s = s + a * vnoise(x * f, y * f, seed + o * 17, px * int(f) if px else None); tot += a; a *= 0.5; f *= 2.0
    return s / tot


def smooth(a, b, t):
    x = np.clip((t - a) / (b - a), 0, 1)
    return x * x * (3 - 2 * x)


def mix(a, b, t): return a + (b - a) * t
def rgb(h): h = h.lstrip("#"); return np.array([int(h[i:i + 2], 16) for i in (0, 2, 4)], dtype=np.float64)
def paint(shape, col): return np.ones(shape + (3,)) * rgb(col)


def lay(img, col, a):
    c = rgb(col) if isinstance(col, str) else col
    return img * (1 - a[..., None]) + c * a[..., None]


def save(name, img, mode="RGB"):
    Image.fromarray(np.clip(img, 0, 255).astype(np.uint8), mode).save(tex / name); print("wrote", name)


def river_x(z): return -10.0 + 5.0 * np.sin(z / 42.0)          # the channel's middle line
def river_d(x, z): return np.abs(x - river_x(z)) - 8.5        # studs outside the water's edge (negative in the river)


def wall(x, z):
    """Height of the canyon walls: they stand back from the river, rise in rounded ledges, and fall away where the canyon opens."""
    left = smooth(-30, -66, x + 6 * np.sin(z / 55.0) + (fbm(x * 0.02, z * 0.02, 7) - 0.5) * 14)
    right = smooth(24, 58, x - 5 * np.sin(z / 48.0 + 1.0) + (fbm(x * 0.02, z * 0.02, 8) - 0.5) * 14)
    open_ = 1 - 0.8 * smooth(-150, -330, z)                      # far down-river the canyon opens on the hills
    raw = np.maximum(left, right) * open_
    h = raw * 78.0
    return h + 2.2 * np.sin(h * 0.75) * smooth(2, 12, h) * (1 - smooth(64, 77, h))   # ledges (the plateau on top is level): the wall steps in and out with height, as water cut it


def hills(x, z):
    def mass(cx, cz, H, R): return H * np.clip(1 - np.hypot(x - cx, z - cz) / R, 0, 1) ** 1.4
    return mass(-260, -900, 210, 520) + mass(320, -1050, 250, 560) + mass(20, -1450, 300, 640) + mass(-800, -400, 120, 500) + mass(820, -420, 120, 500)


def G(x, z):
    x = np.asarray(x, dtype=np.float64); z = np.asarray(z, dtype=np.float64)
    d = river_d(x, z)
    bar = 0.18 + (fbm(x * 0.09, z * 0.09, 1) - 0.5) * 0.5 + (fbm(x * 0.03, z * 0.03, 2) - 0.5) * 1.0   # gravel bars, gently humped
    flat = smooth(7, 16, np.hypot(x - 1.5, np.where(z < 0, z, z * 0.3)))                              # the action's ground is level
    bar = mix(0.2, bar, flat)
    bed = WATER_Y - 0.75 - 0.5 * smooth(0, -6, d) + (fbm(x * 0.2, z * 0.2, 3) - 0.5) * 0.25
    h = np.where(d < 0, mix(WATER_Y - 0.1, bed, smooth(0, -2.5, d)), mix(WATER_Y - 0.1, bar, smooth(0, 3.5, d)))
    return h + wall(x, z) + hills(x, z) * smooth(-200, -420, z)


def grid(rect, n):
    x0, z0, x1, z1 = rect
    return np.meshgrid(np.linspace(x0, x1, n + 1), np.linspace(z0, z1, n + 1))


def pixels(rect, size):
    x0, z0, x1, z1 = rect
    xs = x0 + (np.arange(size) + 0.5) / size * (x1 - x0); zs = z0 + (np.arange(size) + 0.5) / size * (z1 - z0)
    return np.meshgrid(xs, zs)


rng = np.random.default_rng(23)

# ---------------- heights ----------------
NX, NZ = grid(NEAR, N); FX, FZ = grid(FAR, N)
out = {"waterY": WATER_Y, "near": {"rect": NEAR, "h": np.round(G(NX, NZ), 3).tolist()}, "far": {"rect": FAR, "h": np.round(G(FX, FZ) - 3.0, 2).tolist()}}
(tex / "stone_terrain.mjs").write_text("// GENERATED by design3d/stone_world.py. Do not edit by hand.\nexport default " + json.dumps(out, separators=(",", ":")) + ";\n", encoding="utf-8")
print("wrote stone_terrain.mjs")


def strata(h, n1, n2):
    """Limestone colour by height: cream and warm white bands with thin grey-rose seams (measured on the reference)."""
    band = np.sin(h * 0.62 + n1 * 3.0) * 0.5 + 0.5
    col = mix(rgb("#cdbba4"), rgb("#f3eadb"), band[..., None])
    seam = smooth(0.82, 0.97, np.sin(h * 1.9 + n2 * 4.0) * 0.5 + 0.5)
    col = col * (1 - 0.55 * seam[..., None]) + rgb("#9c877c") * (0.55 * seam[..., None])
    return col * (0.9 + 0.16 * n2[..., None])


