"""Write src/PickModelsData.luau from design3d/picks/picks.json (palettes) and design3d/picks/out_h/ids.txt (the hybrid uploads)."""
import json, os
here = os.path.dirname(os.path.abspath(__file__)); game = os.path.dirname(os.path.dirname(here))
picks = json.load(open(os.path.join(here, "picks.json")))
ids = dict(l.split() for l in open(os.path.join(here, "out_h3", "ids.txt")) if l.strip())
L = ["-- Generated by design3d/picks/make_lua.py (picks.json palettes, out_h/ids.txt uploads of design3d/picks/pick_hybrid.py). Do not edit by hand.",
     "-- model name = { id (Model asset: MeshParts named Part__Role), palette (Role -> Color3) }", "return {"]
for p in picks:
    pal = ", ".join(f'{k} = Color3.fromHex("{v}")' for k, v in p["palette"].items())
    L.append(f'\t{p["name"]} = {{ id = {ids[p["name"]]}, palette = {{ {pal} }} }},')
L.append("}")
open(os.path.join(game, "src", "PickModelsData.luau"), "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
print("wrote", len(picks))
