"""Upload the v17 voxel NPC characters and write src/CharRigData.luau (2026-11-28).
Each design3d/chars/out_vox/<Name>.glb goes up as a Model asset (uploads are pre-approved; tools/upload_asset.py logs them in
tools/uploads.json); the ids land in design3d/chars/out_vox/ids.txt, then the rig data (design3d/chars/rigs_npc.json) is
written as src/CharRigData.luau in the pets' PetRigData format.   python design3d/chars/chars_upload.py [Name ...] [--lua-only]"""
import json, pathlib, re, subprocess, sys
here = pathlib.Path(__file__).resolve().parent
game = here.parent.parent
ws = game.parent.parent
vox = here / "out_vox"
ids_f = vox / "ids.txt"
ids = dict(l.split() for l in ids_f.read_text().splitlines() if len(l.split()) == 2) if ids_f.exists() else {}
rigs = json.load(open(here / "rigs_npc.json"))
names = [a for a in sys.argv[1:] if not a.startswith("--")] or list(rigs)
VENV = ws / "Hunyuan3D" / ".venv" / "Scripts" / "python.exe"
if "--lua-only" not in sys.argv:
    for n in names:
        assert rigs[n]["maxPart"] < 20000, f"{n}: one bone has {rigs[n]['maxPart']} triangles (Roblox caps a MeshPart at 20,000)"
        r = subprocess.run([str(VENV), "-I", str(ws / "tools" / "upload_asset.py"), str(vox / f"{n}.glb"), "--user", "872430111", "--name", f"PD npc {n} v17", "--upload"], capture_output=True, text=True, cwd=ws)
        m = re.search(r"asset id (\d+)", r.stdout)
        if not m:
            sys.exit(f"upload failed for {n}:\n{r.stdout[-800:]}\n{r.stderr[-800:]}")
        ids[n] = m.group(1)
        print(n, "->", m.group(1), flush=True)
        ids_f.write_text("\n".join(f"{k} {v}" for k, v in ids.items()) + "\n")
v3 = lambda v: "Vector3.new(%.3f, %.3f, %.3f)" % tuple(v)
L = ["-- Generated by design3d/chars/chars_upload.py from design3d/chars/rigs_npc.json and out_vox/ids.txt. Do not edit by hand.",
     "-- The v17 voxel NPC characters (design3d/chars/npcs_vox.py), in the pets' PetRigData format: one MeshPart per bone named",
     "-- Part__Tex / Part__Glow ... name = { id (Model asset), height, size, glow, parts = { Part = { parent, pivot, group } }, anchors }",
     "return {"]
for name, d in rigs.items():
    if name not in ids: continue
    parts = ", ".join('["%s"] = { %s, %s, "%s" }' % (p, ('"%s"' % d["parent"][p]) if d["parent"].get(p) else "nil", v3(d["pivots"][p]), d["groups"].get(p, "body")) for p in d["pivots"])
    anchors = ", ".join('["%s"] = { "%s", %s }' % (k, v[0], v3(v[1])) for k, v in d.get("anchors", {}).items())
    glow = d["palette"].get("Glow", "#ffffff"); crystal = d["palette"].get("Crystal", glow)
    L.append('\t["%s"] = { id = %s, height = %.2f, size = %s, glow = Color3.fromHex("%s"), crystal = Color3.fromHex("%s"), vox = true, npc = true, parts = { %s }, axes = { }, anchors = { %s } },'
             % (name, ids[name], d["height"], v3(d["size"]), glow, crystal, parts, anchors))
L.append("}")
open(game / "src" / "CharRigData.luau", "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
print("wrote", len(L) - 5, "characters")
