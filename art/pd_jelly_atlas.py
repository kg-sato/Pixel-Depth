"""Pack the jelly glyph renders (art/jelly_pink, art/jelly_white from pd_logo_jelly.py) into one atlas each (8 columns of
128 px cells) and write the glyph table the game reads (src/JellyGlyphs.luau: cell, columns, each glyph's cell index and its
advance width as a share of the cell).   python art/pd_jelly_atlas.py"""
import pathlib
from PIL import Image

here = pathlib.Path(__file__).resolve().parent
CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!?+%:-/.',()&<>="
NAMES = {"!": "bang", "?": "ask", "+": "plus", "%": "pct", ":": "colon", "-": "dash", "/": "slash", ".": "dot", "'": "apos", ",": "comma", "(": "lpar", ")": "rpar", "&": "amp", "<": "lt", ">": "gt", "=": "eq"}
CELL, COLS = 128, 8


def load(folder):
    return {ch: Image.open(here / folder / (NAMES.get(ch, ch) + ".png")).convert("RGBA") for ch in CHARS}


pink = load("jelly_pink")
src = pink["A"].size[0]
# one square crop for every glyph, centred on the cell: as tall as the tallest capital, as wide as the widest glyph
top, bot, wide = src, 0, 0
boxes = {}
for ch, im in pink.items():
    b = im.split()[3].point(lambda a: 255 if a > 24 else 0).getbbox()
    boxes[ch] = b
    if ch.isalnum(): top, bot = min(top, b[1]), max(bot, b[3])
    wide = max(wide, b[2] - b[0])
side = max(bot - top, wide) + 10
cy = (top + bot) // 2
crop = (src // 2 - side // 2, cy - side // 2, src // 2 - side // 2 + side, cy - side // 2 + side)
print("source", src, "crop side", side, crop)

rows = (len(CHARS) + COLS - 1) // COLS
adv = {}
for folder, glyphs in (("jelly_pink", pink), ("jelly_white", load("jelly_white"))):
    atlas = Image.new("RGBA", (COLS * CELL, rows * CELL), (0, 0, 0, 0))
    for i, ch in enumerate(CHARS):
        g = glyphs[ch].crop(crop).resize((CELL, CELL), Image.LANCZOS)
        atlas.alpha_composite(g, ((i % COLS) * CELL, (i // COLS) * CELL))
        if folder == "jelly_pink":
            b = boxes[ch]
            adv[ch] = round(((b[2] - b[0]) / side) * 0.9 + 0.02, 3)  # the puffy rims overlap a little: letters sit close like the reference
    atlas.save(here / folder / "_atlas.png")
    bg = Image.new("RGBA", atlas.size, (22, 8, 30, 255)); bg.alpha_composite(atlas); bg.convert("RGB").save(here / folder / "_atlas_preview.jpg", quality=88)

lua = ["-- JellyGlyphs (ReplicatedStorage.Shared.JellyGlyphs): generated by art/pd_jelly_atlas.py, do not edit by hand.",
       "-- The jelly font atlas: 128 px cells, 8 columns. index = cell number from 0, adv = advance width as a share of the cell, cap = a capital's height as a share of the cell.",
       "return { cell = %d, cols = %d, rows = %d, cap = %.3f, glyphs = {" % (CELL, COLS, rows, (bot - top) / side)]
for i, ch in enumerate(CHARS):
    lua.append('\t[%s] = { %d, %s },' % ('"' + ch + '"', i, adv[ch]))
lua.append("} }")
(here.parent / "src" / "JellyGlyphs.luau").write_text("\n".join(lua) + "\n", encoding="utf-8")
print("atlas", COLS * CELL, rows * CELL, "glyphs", len(CHARS))
