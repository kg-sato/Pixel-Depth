"""Build, upload and install the forge biography models of one scene (Pixel Depth, brief "Forge Biographies (2026-11-15)").
    python spike/forge_install.py wood            export, write GLBs, upload changed models, install in ReplicatedStorage.ForgeModels,
                                                  and rewrite src/ForgeRigs.luau (rig data for every installed scene)
    python spike/forge_install.py wood --local    export and rig data only (no upload, no Studio)
Asset ids are kept in design3d/assets.json (keyed by model, with the GLB hash, so an unchanged model is not uploaded again)."""
import hashlib, json, pathlib, subprocess, sys
game = pathlib.Path(__file__).resolve().parent.parent
root = game.parent.parent
sys.path.insert(0, str(game / "spike"))
scene = sys.argv[1]
local = "--local" in sys.argv
out = game / "design3d" / "out"
r = subprocess.run(["node", str(game / "design3d" / "export.mjs"), scene, str(out)], capture_output=True, text=True, cwd=game)
print(r.stdout.strip() or r.stderr.strip())
if r.returncode: sys.exit(1)
rig = json.loads((out / f"{scene}_rig.json").read_text(encoding="utf-8"))
assets_p = game / "design3d" / "assets.json"
assets = json.loads(assets_p.read_text(encoding="utf-8")) if assets_p.exists() else {}

# rig data: Roblox space is the authoring space turned half a turn about Y (x and z flip), as the GLB import does
rigs_p = game / "design3d" / "rigs.json"
rigs = json.loads(rigs_p.read_text(encoding="utf-8")) if rigs_p.exists() else {}
for name, m in rig.items(): rigs[name] = m
rigs_p.write_text(json.dumps(rigs, separators=(",", ":")), encoding="utf-8")
v3 = lambda p: "Vector3.new(%s, %s, %s)" % (round(-p[0], 3), round(p[1], 3), round(-p[2], 3))
lines = ["-- GENERATED by spike/forge_install.py from design3d/*.mjs. Do not edit by hand.", "-- Rig data of the forge biography models: per bone its parent, joint and mesh centre (Roblox space, model front is -Z).", "return {"]
for name in sorted(rigs):
    lines.append(f"\t{name} = {{")
    for b in rigs[name]["bones"]:
        par = f'"{b["parent"]}"' if b.get("parent") else "nil"
        if b.get("empty"): lines.append(f'\t\t{{ name = "{b["name"]}", parent = {par}, joint = {v3(b["joint"])} }},')
        else: lines.append(f'\t\t{{ name = "{b["name"]}", parent = {par}, joint = {v3(b["joint"])}, center = {v3(b["center"])}, size = Vector3.new({b["size"][0]}, {b["size"][1]}, {b["size"][2]}), mat = "{b["mat"]}", color = "{b["color"]}" }},')
    lines.append("\t},")
lines.append("}")
(game / "src" / "ForgeRigs.luau").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print("rig data:", len(rigs), "models")
if local: sys.exit(0)

import night as N
py = root / "Hunyuan3D" / ".venv" / "Scripts" / "python.exe"
for name in rig:
    subprocess.run([sys.executable, str(root / "tools" / "design3d" / "write_glb.py"), str(out / f"{name}.json"), str(out / f"{name}.glb")], capture_output=True, text=True, check=True)
    h = hashlib.sha1((out / f"{name}.json").read_bytes()).hexdigest()[:12]
    if assets.get(name, {}).get("hash") != h:
        u = subprocess.run([str(py), "-I", str(root / "tools" / "upload_asset.py"), str(out / f"{name}.glb"), "--user", "872430111", "--name", "PD Forge " + name, "--upload"], capture_output=True, text=True, cwd=root)
        tail = (u.stdout + u.stderr).strip().splitlines()[-1]
        if "asset id" not in tail: sys.exit(f"upload failed for {name}: {tail}")
        assets[name] = {"id": tail.split("asset id")[1].split()[0], "hash": h}
        assets_p.write_text(json.dumps(assets, indent=1), encoding="utf-8")
        print("uploaded", name, assets[name]["id"])
    bones = {b["name"]: [b["mat"], b["color"]] for b in rig[name]["bones"] if not b.get("empty")}
    code = """
local name, id, bones = "%s", %s, game:GetService("HttpService"):JSONDecode([==[%s]==])
local ok, raw = pcall(function() return game:GetService("InsertService"):LoadAsset(id) end)
if not ok then return "ERR " .. tostring(raw) end
local f = game.ReplicatedStorage:FindFirstChild("ForgeModels") or Instance.new("Folder")
f.Name = "ForgeModels" f.Parent = game.ReplicatedStorage
local old = f:FindFirstChild(name) if old then old:Destroy() end
local m = Instance.new("Model") m.Name = name
local n = 0
for _, p in raw:GetDescendants() do
	if p:IsA("MeshPart") and bones[p.Name] then
		local b = bones[p.Name]
		p.Anchored, p.CanCollide, p.CanQuery, p.CanTouch, p.Massless = true, false, false, false, true
		p.Material = (b[1] == "Neon" and Enum.Material.Neon) or (b[1] == "Glass" and Enum.Material.Glass) or Enum.Material.SmoothPlastic
		p.Color = b[1] == "Neon" and Color3.fromHex(b[2]) or Color3.new(1, 1, 1)
		if b[1] == "Neon" then p.TextureID = "" end
		p.CastShadow = b[1] ~= "Neon"
		local sa = p:FindFirstChildOfClass("SurfaceAppearance") if sa then sa:Destroy() end
		p.Parent = m n += 1
	end
end
m.Parent = f raw:Destroy()
return name .. " installed, " .. n .. " parts"
""" % (name, assets[name]["id"], json.dumps(bones))
    print(N.lua(code, "Edit").splitlines()[-1])
